import { expect, test } from '@playwright/test'
import { saveFixtureGradeCP } from './report-grade-cp-fixture'

test('admin enables paper recap, wali fills totals, and final reports stay frozen', async ({ page, request, context }) => {
  test.skip(process.env.E2E_RAPOR_ISOLATED !== '1', 'Requires a fresh in-memory report browser harness.')
  expect(await (await request.get('/__report-audit')).json()).toMatchObject({ isolated: true, storage: 'memory' })
  await context.addInitScript(() => localStorage.setItem('pkbmti-lms-install-prompt:last-dismissed-at', String(Date.now())))
  async function login(username: string, password: string) {
    await page.goto('/')
    await page.getByPlaceholder('Masukkan username atau email').fill(username)
    await page.getByPlaceholder('Masukkan password').fill(password)
    const response = page.waitForResponse(r => r.url().endsWith('/api/auth/login') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Masuk', exact: true }).click()
    const { accessToken } = await (await response).json()
    await expect(page).toHaveURL(/dashboard/)
    return accessToken as string
  }
  const token = await login('admin', 'Admin123')
  const headers = { Authorization: `Bearer ${token}` }
  await page.getByRole('navigation', { name: 'Menu aplikasi', exact: true }).getByRole('link', { name: 'Rapor', exact: true }).click()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  const classId = await page.getByLabel('Kelas rapor').inputValue()
  const qs = `?kelasId=${classId}&semester=Ganjil`
  await page.getByRole('button', { name: 'Presensi rapor', exact: true }).click()
  await expect(page.getByLabel('Sumber presensi rapor')).toHaveValue('automatic')
  await expect(page.getByLabel('Sakit Siswa A', { exact: true })).toHaveCount(0)
  await page.getByLabel('Sumber presensi rapor').selectOption('manual')
  await expect(page.getByLabel('Sakit Siswa A', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Izin Siswa A', { exact: true })).toHaveValue('')
  await page.getByLabel('Sakit Siswa A', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Simpan rekap presensi', exact: true }).click()
  await expect(page.getByText(/Lengkapi Sakit, Izin, dan Alpa dengan bilangan bulat/)).toBeVisible()
  await page.getByLabel('Sakit Siswa B', { exact: true }).fill('0')
  await page.getByLabel('Izin Siswa B', { exact: true }).fill('0')
  const saveCompleteRow = page.waitForResponse(response => response.url().includes('/api/rapor-sumatif/attendance?') && response.request().method() === 'PUT' && response.ok())
  await page.getByLabel('Alpa Siswa B', { exact: true }).fill('0')
  await saveCompleteRow
  const attendance = await (await request.get('/api/rapor-sumatif/attendance' + qs, { headers })).json()
  expect(attendance.rows.map((row: { manual: unknown }) => row.manual)).toEqual(expect.arrayContaining([null, { sakit: 0, izin: 0, alpa: 0 }]))
  await expect(page.getByLabel('Izin Siswa A', { exact: true })).toHaveValue('')
  await page.getByLabel('Izin Siswa A', { exact: true }).fill('2')
  await page.getByLabel('Alpa Siswa A', { exact: true }).fill('0')
  await expect(page.getByRole('status').getByText('Presensi tersimpan otomatis.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Simpan rekap presensi', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Sakit Siswa A', { exact: true })).toHaveValue('3')
  await expect(page.getByText(/Lengkapi Sakit, Izin, dan Alpa dengan bilangan bulat/)).toHaveCount(0)
  if (process.env.E2E_REPORT_OUTPUT) await page.screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/admin-rekap-manual.png', fullPage: true })
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · Draf' })
  await expect(page.getByText('Ketidakhadiran: Sakit 3 hari · Izin 2 hari · Tanpa keterangan 0 hari', { exact: true })).toBeVisible()
  await expect(page.getByText(/Sumber presensi: rekap manual dari catatan kertas/)).toBeVisible()
  await page.getByLabel('Catatan wali kelas', { exact: true }).fill('Catatan wali tetap tersimpan.')
  await page.getByRole('button', { name: 'Simpan catatan', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Simpan catatan', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Presensi rapor', exact: true }).click()
  await page.getByLabel('Sumber presensi rapor').selectOption('automatic')
  await page.getByRole('button', { name: 'Simpan sumber presensi', exact: true }).click()
  await expect(page.getByLabel('Sakit Siswa A', { exact: true })).toHaveCount(0)
  await page.getByLabel('Sumber presensi rapor').selectOption('manual')
  await page.getByRole('button', { name: 'Simpan sumber presensi', exact: true }).click()
  await expect(page.getByLabel('Sakit Siswa A', { exact: true })).toHaveValue('3')
  // Prepare a complete report through the same public API used by the UI.
  let state = await (await request.get('/api/rapor-sumatif/period' + qs, { headers })).json()
  const mapelId = state.config.subjects[0].mapelId
  let result = await request.put('/api/rapor-sumatif/config' + qs, { headers, data: { revision: state.period.revision, config: { ...state.config, date: '2026-12-20', teacher: 'Tutor Contoh' } } })
  expect(result.status()).toBe(200)
  await saveFixtureGradeCP(request, token, classId, mapelId, ['membaca kata'])
  const grid = await (await request.get('/api/rapor-sumatif/grid' + qs + '&mapelId=' + mapelId, { headers })).json()
  result = await request.put('/api/rapor-sumatif/grid' + qs + '&mapelId=' + mapelId, { headers, data: { revision: grid.period.revision, cps: grid.cps, scores: grid.students.map((s: { id: string }) => ({ studentId: s.id, cpId: grid.cps[0].id, value: 85 })), narratives: [] } })
  expect(result.status()).toBe(200)
  const studentId = grid.students.find((s: { nama: string }) => s.nama === 'Siswa A').id
  for (const status of ['ready', 'final', 'published']) {
    state = await (await request.get('/api/rapor-sumatif/period' + qs, { headers })).json()
    result = await request.post(`/api/rapor-sumatif/document/${studentId}/status${qs}`, { headers, data: { revision: state.period.revision, status } })
    expect(result.status(), await result.text()).toBe(200)
  }
  const pdf = await request.get(`/api/rapor-sumatif/print${qs}&studentId=${studentId}&kind=rapor`, { headers })
  expect(pdf.status()).toBe(200)
  expect(pdf.headers()['content-type']).toContain('application/pdf')
  if (process.env.E2E_REPORT_OUTPUT) await (await import('node:fs/promises')).writeFile(process.env.E2E_REPORT_OUTPUT + '/rapor-rekap-manual.pdf', await pdf.body())
  await context.clearCookies()
  await page.evaluate(() => localStorage.clear())
  await login('wali-rapor', 'Guru12345')
  await page.getByRole('navigation', { name: 'Menu aplikasi', exact: true }).getByRole('link', { name: 'Rapor', exact: true }).click()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  await page.getByRole('button', { name: 'Presensi rapor', exact: true }).click()
  await expect(page.getByLabel('Sumber presensi rapor')).toHaveCount(0)
  await expect(page.getByText('Rapor final / terbit', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Sakit Siswa A', { exact: true })).toHaveCount(0)
  await page.getByLabel('Izin Siswa B', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Simpan rekap presensi', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Simpan rekap presensi', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Izin Siswa B', { exact: true })).toHaveValue('1')
  if (process.env.E2E_REPORT_OUTPUT) await page.screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/wali-rekap-manual.png', fullPage: true })
})
