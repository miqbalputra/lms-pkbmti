import { expect, test } from '@playwright/test'
import { saveFixtureGradeCP } from './report-grade-cp-fixture'

test.use({ actionTimeout: 15_000 })

test('isian aman, pemeriksaan terbaru, kunci periode jelas, dan panduan wajib', async ({ page, request, context }) => {
  test.skip(process.env.E2E_RAPOR_ISOLATED !== '1', 'Requires a fresh in-memory report browser fixture.')
  expect(await (await request.get('/__report-audit')).json()).toMatchObject({ isolated: true, storage: 'memory' })
  await context.addInitScript(() => localStorage.setItem('pkbmti-lms-install-prompt:last-dismissed-at', String(Date.now())))
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByPlaceholder('Masukkan username atau email').fill('admin')
  await page.getByPlaceholder('Masukkan password').fill('Admin123')
  const login = page.waitForResponse(r => r.url().endsWith('/api/auth/login') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Masuk', exact: true }).click()
  const { accessToken } = await (await login).json()
  const headers = { Authorization: `Bearer ${accessToken}` }
  const classes = await (await request.get('/api/rapor-sumatif/classes', { headers })).json()
  const klass = classes.find((k: { namaRombel: string }) => k.namaRombel === 'R')
  const qs = `?kelasId=${klass.id}&semester=Ganjil`
  async function period() { return (await request.get('/api/rapor-sumatif/period' + qs, { headers })).json() }
  let state = await period()
  let response = await request.put('/api/rapor-sumatif/config' + qs, { headers, data: { revision: state.period.revision, config: { ...state.config, date: '2026-12-19', teacher: 'Wali Contoh', principal: 'Kepala Contoh' } } })
  expect(response.status()).toBe(200)
  state = await period()
  const mapel = state.config.subjects[0].mapelId
  await saveFixtureGradeCP(request, accessToken, klass.id, mapel, ['membaca kata', 'menulis kalimat'])
  let grid = await (await request.get('/api/rapor-sumatif/grid' + qs + '&mapelId=' + mapel, { headers })).json()
  response = await request.put('/api/rapor-sumatif/grid' + qs + '&mapelId=' + mapel, { headers, data: { revision: grid.period.revision, cps: grid.cps, scores: grid.students.flatMap((s: { id: string; nama: string }) => grid.cps.map((cp: { id: string }, i: number) => ({ studentId: s.id, cpId: cp.id, value: s.nama === 'Siswa B' ? [88, 80][i] : 90 }))), narratives: [] } })
  expect(response.status()).toBe(200)
  const studentA = grid.students.find((s: { nama: string }) => s.nama === 'Siswa A')
  const studentB = grid.students.find((s: { nama: string }) => s.nama === 'Siswa B')
  const nav = page.getByRole('navigation', { name: 'Menu aplikasi', exact: true })
  async function chooseNilai() {
    await nav.getByRole('link', { name: 'Modul Nilai', exact: true }).click()
    await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
    await page.getByLabel('Mata pelajaran rapor').selectOption({ label: 'Bahasa Indonesia' })
  }
  async function saved() { await expect(page.getByRole('button', { name: 'Simpan nilai', exact: true })).toBeDisabled() }
  const cell = page.getByLabel('Siswa B CP 1', { exact: true })
  const prompt = page.getByRole('dialog', { name: 'Ada isian yang belum disimpan', exact: true })
  await chooseNilai()
  await expect(page.getByRole('region', { name: 'Langkah pengisian rapor' })).toBeVisible()
  await cell.fill('77')
  await page.getByRole('button', { name: 'Buka nilai tema / arsip alur lama', exact: true }).click()
  await expect(prompt).toBeVisible()
  if (process.env.E2E_REPORT_OUTPUT) await prompt.screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/dialog-isian-aman.png' })
  await prompt.getByRole('button', { name: 'Tetap di halaman', exact: true }).click()
  await expect(cell).toHaveValue('77')
  await page.getByRole('button', { name: 'Buka nilai tema / arsip alur lama', exact: true }).click()
  await prompt.getByRole('button', { name: 'Buang perubahan', exact: true }).click()
  await page.getByRole('button', { name: 'Kembali ke nilai sumatif CP', exact: true }).click()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  await page.getByLabel('Mata pelajaran rapor').selectOption({ label: 'Bahasa Indonesia' })
  await expect(cell).toHaveValue('88')
  // Saving before a router navigation must complete before the form unmounts.
  await cell.fill('66')
  await nav.getByRole('link', { name: 'Rapor', exact: true }).click()
  await expect(prompt).toBeVisible()
  await prompt.getByRole('button', { name: 'Tetap di halaman', exact: true }).click()
  await expect(cell).toHaveValue('66')
  await nav.getByRole('link', { name: 'Rapor', exact: true }).click()
  await prompt.getByRole('button', { name: 'Simpan & lanjutkan', exact: true }).click()
  await expect(page).toHaveURL(/\/rapor$/)
  await expect(page.getByRole('heading', { name: 'Rapor Semester', exact: true })).toBeVisible()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa B · Draf' })
  await expect(page.getByRole('cell', { name: '73', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Nilai & deskripsi', exact: true }).click()
  await page.getByLabel('Mata pelajaran rapor').selectOption({ label: 'Bahasa Indonesia' })
  await cell.fill('60')
  await page.getByRole('button', { name: 'Simpan nilai', exact: true }).click()
  await saved()
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await expect(page.getByRole('cell', { name: '70', exact: true })).toBeVisible()
  const actual = await (await request.get(`/api/rapor-sumatif/document/${studentB.id}${qs}`, { headers })).json()
  expect(actual.document.subjects[0].score).toBe(70)
  await expect(page.getByRole('cell', { name: '73', exact: true })).toHaveCount(0)
  // Browser Back is guarded as well as links and archive buttons.
  await page.getByLabel('Catatan wali kelas', { exact: true }).fill('Catatan yang belum disimpan')
  await page.goBack()
  await expect(prompt).toBeVisible()
  await prompt.getByRole('button', { name: 'Tetap di halaman', exact: true }).click()
  await expect(page.getByLabel('Catatan wali kelas', { exact: true })).toHaveValue('Catatan yang belum disimpan')
  await page.getByRole('button', { name: 'Pengaturan', exact: true }).click()
  await prompt.getByRole('button', { name: 'Simpan & lanjutkan', exact: true }).click()
  await expect(page.getByLabel('Tanggal rapor', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Tanggal rapor', { exact: true })).toHaveAttribute('aria-required', 'true')
  await expect(page.getByLabel('NIP wali kelas', { exact: true })).toHaveAttribute('aria-required', 'false')
  if (process.env.E2E_REPORT_OUTPUT) await page.locator('#report-config').screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/isian-wajib.png' })
  // AI settings are pending inputs too; leaving may discard them without calling AI.
  await page.getByLabel('ID model', { exact: true }).fill('model-belum-disimpan')
  await page.getByRole('button', { name: 'Nilai & deskripsi', exact: true }).click()
  await expect(prompt).toBeVisible()
  await prompt.getByRole('button', { name: 'Buang perubahan', exact: true }).click()
  await cell.fill('101')
  await nav.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await prompt.getByRole('button', { name: 'Simpan & lanjutkan', exact: true }).click()
  await expect(prompt.getByRole('alert')).toContainText('0–100')
  await expect(cell).toHaveValue('101')
  await prompt.getByRole('button', { name: 'Tetap di halaman', exact: true }).click()
  await cell.fill('61')
  await page.route('**/api/rapor-sumatif/grid?*', route => route.request().method() === 'PUT' ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Gangguan uji sementara' }) }) : route.continue())
  await nav.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await prompt.getByRole('button', { name: 'Simpan & lanjutkan', exact: true }).click()
  await expect(prompt.getByRole('alert')).toContainText('Gangguan uji sementara')
  await expect(cell).toHaveValue('61')
  await page.unroute('**/api/rapor-sumatif/grid?*')
  await prompt.getByRole('button', { name: 'Tetap di halaman', exact: true }).click()
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await prompt.getByRole('button', { name: 'Buang perubahan', exact: true }).click()
  await expect(page.getByRole('cell', { name: '70', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Nilai & deskripsi', exact: true }).click()
  await cell.evaluate(input => {
    const data = new DataTransfer(); data.setData('text/plain', '10\t130')
    input.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
  })
  await expect(page.getByRole('alert')).toContainText('Blok berisi nilai tidak valid')
  await expect(cell).toHaveValue('60')
  // Changing a filter keeps the requested destination, after saving the old scope.
  await cell.fill('61')
  await cell.fill('60')
  await page.getByLabel('Semester rapor').selectOption('Genap')
  await prompt.getByRole('button', { name: 'Tetap di halaman', exact: true }).click()
  await expect(page.getByLabel('Semester rapor')).toHaveValue('Ganjil')
  await expect(cell).toHaveValue('60')
  await page.getByLabel('Semester rapor').selectOption('Genap')
  await prompt.getByRole('button', { name: 'Simpan & lanjutkan', exact: true }).click()
  await expect(page.getByLabel('Semester rapor')).toHaveValue('Genap')
  const otherSemester = await (await request.get(`/api/rapor-sumatif/grid?kelasId=${klass.id}&semester=Genap&mapelId=${mapel}`, { headers })).json()
  expect(otherSemester.cps).toHaveLength(0)
  await page.getByLabel('Semester rapor').selectOption('Ganjil')
  await page.getByLabel('Mata pelajaran rapor').selectOption({ label: 'Bahasa Indonesia' })
  await expect(cell).toHaveValue('60')
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa B · Draf' })
  // Completeness links lead to the right panel and saving attendance can continue.
  await page.getByRole('button', { name: 'Presensi rapor', exact: true }).click()
  await page.getByLabel('Sumber presensi rapor').selectOption('manual')
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await prompt.getByRole('button', { name: 'Simpan & lanjutkan', exact: true }).click()
  await page.getByRole('button', { name: /Lengkapi rekap presensi manual:/ }).click()
  await expect(page.getByRole('heading', { name: 'Presensi untuk rapor', exact: true })).toBeVisible()
  for (const name of ['Siswa A', 'Siswa B']) for (const field of ['Sakit', 'Izin', 'Alpa']) await page.getByLabel(`${field} ${name}`, { exact: true }).fill(field === 'Sakit' ? '2' : '0')
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await prompt.getByRole('button', { name: 'Simpan & lanjutkan', exact: true }).click()
  await expect(page.getByText('Ketidakhadiran: Sakit 2 hari · Izin 0 hari · Tanpa keterangan 0 hari', { exact: true })).toBeVisible()
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · Draf' })
  for (const name of ['Siap diperiksa', 'Finalkan rapor', 'Terbitkan untuk orang tua']) {
    const button = page.getByRole('button', { name, exact: true })
    await expect(button).toBeEnabled()
    await button.click()
    if (name === 'Siap diperiksa') await expect(page.getByText('Siap diperiksa wali kelas', { exact: true })).toBeVisible()
    if (name === 'Finalkan rapor') await expect(page.getByText('Final · versi terkunci', { exact: true })).toBeVisible()
  }
  await expect(page.getByText('Terbit · tersedia untuk orang tua', { exact: true })).toBeVisible()
  const frozen = await (await request.get(`/api/rapor-sumatif/document/${studentA.id}${qs}`, { headers })).json()
  await page.getByRole('button', { name: 'Pengaturan', exact: true }).click()
  await expect(page.getByText('Pengaturan kelas dikunci', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Tanggal rapor', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Simpan pengaturan', exact: true })).toBeDisabled()
  if (process.env.E2E_REPORT_OUTPUT) await page.locator('#report-config').screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/pengaturan-terkunci.png' })
  await page.getByRole('button', { name: 'Nilai & deskripsi', exact: true }).click()
  await expect(cell).toBeEnabled()
  await expect(page.getByLabel('Siswa A CP 1', { exact: true })).toBeDisabled()
  const semesters = await (await request.get('/api/semester?tahunAjaranId=' + klass.tahunAjaranId, { headers })).json()
  const semester = semesters.find((s: { namaSemester: string }) => s.namaSemester === 'Ganjil')
  expect((await request.put('/api/semester/' + semester.id, { headers, data: { isArchived: true } })).status()).toBe(200)
  await page.reload()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  await page.getByRole('button', { name: 'Nilai & deskripsi', exact: true }).click()
  await page.getByLabel('Mata pelajaran rapor').selectOption({ label: 'Bahasa Indonesia' })
  await expect(page.getByText(/Semester ini sudah diarsipkan/)).toBeVisible()
  await expect(cell).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Simpan nilai', exact: true })).toHaveCount(0)
  const unchanged = await (await request.get(`/api/rapor-sumatif/document/${studentA.id}${qs}`, { headers })).json()
  expect(unchanged.document).toEqual(frozen.document)
  if (process.env.E2E_REPORT_OUTPUT) await page.screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/semester-arsip.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Panduan langkah demi langkah', exact: true })).toBeVisible()
  expect(errors).toEqual([])
  grid = await (await request.get('/api/rapor-sumatif/grid' + qs + '&mapelId=' + mapel, { headers })).json()
  expect(grid.scores.find((s: { studentId: string; cpId: string }) => s.studentId === studentB.id && s.cpId === grid.cps[0].id).value).toBe(60)
})
