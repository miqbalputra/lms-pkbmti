  await page.getByLabel('Siswa A CP 2', { exact: true }).fill('85.5')
  await page.getByLabel('Siswa B CP 1', { exact: true }).fill('90')
  await page.getByLabel('Siswa B CP 2', { exact: true }).fill('80')
  await page.getByLabel('Capaian Siswa A', { exact: true }).fill('Ananda mampu membaca teks dan menulis kalimat sederhana.')
  await page.getByRole('button', { name: 'Simpan nilai', exact: true }).click()
  await expect(page.getByLabel('Capaian Siswa A', { exact: true })).toHaveValue('Ananda mampu membaca teks dan menulis kalimat sederhana.')
  await page.getByRole('button', { name: 'Pengaturan', exact: true }).click()
  await page.getByLabel('Tanggal rapor', { exact: true }).fill('2026-06-01')
  await page.getByRole('button', { name: 'Tambah kegiatan kelas', exact: true }).click()
  await page.getByLabel('Kegiatan kelas 1', { exact: true }).fill('Pramuka')
  await page.getByRole('button', { name: 'Tambah kegiatan kelas', exact: true }).click()
  await page.getByLabel('Kegiatan kelas 2', { exact: true }).fill('Seni Tari')
  const reportAutoSaved = page.getByRole('status').getByText('Tersimpan otomatis', { exact: true })
  await expect(reportAutoSaved).toBeVisible()
  await page.getByLabel('ID model', { exact: true }).fill('model-uji-rapor')
  await expect(reportAutoSaved).toBeVisible()
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · Draf' })
