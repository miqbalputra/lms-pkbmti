import { expect, test } from '@playwright/test'

test('kelas tujuan otomatis dan kelulusan terpisah tanpa mengetik kelas tujuan', async ({ page, request, context }) => {
  test.skip(process.env.E2E_PROMOTION_ISOLATED !== '1', 'Requires TestReportPromotionBrowserServer in-memory fixture.')
  expect(await (await request.get('/__report-audit')).json()).toMatchObject({ isolated: true, storage: 'memory' })
  await context.addInitScript(() => localStorage.setItem('pkbmti-lms-install-prompt:last-dismissed-at', String(Date.now())))
  await page.goto('/')
  await page.getByPlaceholder('Masukkan username atau email').fill('admin')
  await page.getByPlaceholder('Masukkan password').fill('Admin123')
  const login = page.waitForResponse(r => r.url().endsWith('/api/auth/login') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Masuk', exact: true }).click()
  const { accessToken } = await (await login).json()
  const headers = { Authorization: `Bearer ${accessToken}` }
  await expect(page).toHaveURL(/dashboard/)
  await page.getByRole('navigation', { name: 'Menu aplikasi', exact: true }).getByRole('link', { name: 'Rapor', exact: true }).click()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  await page.getByLabel('Semester rapor').selectOption('Genap')
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · Draf' })
  await page.getByLabel('Keputusan kenaikan', { exact: true }).selectOption('naik')
  await expect(page.getByLabel('Kelas tujuan kenaikan', { exact: true })).toHaveText('II (Dua)')
  await expect(page.getByRole('textbox', { name: 'Naik ke kelas', exact: true })).toHaveCount(0)
  async function save() {
    const response = page.waitForResponse(r => /rapor-sumatif\/document\//.test(r.url()) && r.request().method() === 'PUT')
    await page.getByRole('button', { name: 'Simpan catatan', exact: true }).click()
    expect((await response).status()).toBe(200)
    await expect(page.getByRole('button', { name: 'Simpan catatan', exact: true })).toBeDisabled()
  }
  await save()
  if (process.env.E2E_REPORT_OUTPUT) await page.screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/kelas-tujuan-otomatis.png', fullPage: true })
  await page.getByLabel('Keputusan kenaikan', { exact: true }).selectOption('tinggal')
  await expect(page.getByLabel('Kelas tujuan kenaikan', { exact: true })).toHaveCount(0)
  await save()
  await page.getByLabel('Keputusan kenaikan', { exact: true }).selectOption('naik')
  await save()
  const classId = await page.getByLabel('Kelas rapor').inputValue()
  const studentId = await page.getByLabel('Peserta didik rapor').inputValue()
  const qs = `?kelasId=${classId}&semester=Genap`
  let data = await (await request.get(`/api/rapor-sumatif/document/${studentId}${qs}`, { headers })).json()
  expect(data.document.details).toMatchObject({ promotion: 'naik', nextClass: 'II (Dua)' })
  // A fresh reload restores the saved automatic target.
  await page.reload()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  await page.getByLabel('Semester rapor').selectOption('Genap')
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · Draf' })
  await expect(page.getByLabel('Kelas tujuan kenaikan', { exact: true })).toHaveText('II (Dua)')
  await page.getByLabel('Semester rapor').selectOption('Ganjil')
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · Draf' })
  await expect(page.getByLabel('Keputusan kenaikan', { exact: true })).toHaveCount(0)
  for (const grade of [6, 9, 12]) {
    await page.getByLabel('Kelas rapor').selectOption({ label: `Kelas ${grade} DEMO` })
    await page.getByLabel('Semester rapor').selectOption('Genap')
    await page.getByLabel('Peserta didik rapor').selectOption({ label: `Siswa Contoh Kelas ${grade} · Draf` })
    await expect(page.getByLabel('Keputusan kenaikan', { exact: true })).toHaveCount(0)
    await expect(page.getByLabel('Keputusan kelulusan', { exact: true })).toHaveValue('')
    await expect(page.getByLabel('Keputusan kelulusan', { exact: true }).locator('option')).toHaveText(['Belum ditentukan', 'Lulus', 'Belum lulus'])
    await page.getByLabel('Keputusan kelulusan', { exact: true }).selectOption('lulus')
    await expect(page.getByLabel('Kelas tujuan kenaikan', { exact: true })).toHaveCount(0)
    await save()
    const cid = await page.getByLabel('Kelas rapor').inputValue()
    const sid = await page.getByLabel('Peserta didik rapor').inputValue()
    data = await (await request.get(`/api/rapor-sumatif/document/${sid}?kelasId=${cid}&semester=Genap`, { headers })).json()
    expect(data.document.details).toMatchObject({ promotion: 'lulus', nextClass: '' })
    if (grade === 12 && process.env.E2E_REPORT_OUTPUT) await page.screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/keputusan-kelulusan.png', fullPage: true })
    await page.getByLabel('Keputusan kelulusan', { exact: true }).selectOption('belum_lulus')
    await save()
    await expect(page.getByLabel('Keputusan kelulusan', { exact: true })).toHaveValue('belum_lulus')
  }
})
