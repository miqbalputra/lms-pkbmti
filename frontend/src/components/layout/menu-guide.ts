export function matchesMenu(item: NavItem, query: string) {
  const haystack = [item.label, item.id, MENU_GUIDES[item.id], ALIASES[item.id]].filter(Boolean).join(' ').toLocaleLowerCase('id')
  return query.trim().toLocaleLowerCase('id').split(/\s+/).every(word => haystack.includes(word))
}
