import { expect, test } from '@playwright/test'

test.beforeEach(async ({ request, context }) => {
  test.skip(process.env.E2E_RAPOR_ISOLATED !== '1', 'Requires the in-memory report browser harness.')
  expect(await (await request.get('/__report-audit')).json()).toMatchObject({ isolated: true, storage: 'memory' })
  await context.addInitScript(() => localStorage.setItem('pkbmti-lms-install-prompt:last-dismissed-at', String(Date.now())))
})

test('alur sumatif CP sampai rapor terbit dan PDF kelas', async ({ page }) => {
  test.skip(process.env.E2E_RAPOR_ISOLATED !== '1', 'Jalankan dengan harness TestReportBrowserServer yang memakai database terisolasi.')
  await page.goto('/')
  await page.getByPlaceholder('Masukkan username atau email').fill('admin')
  await page.getByPlaceholder('Masukkan password').fill('Admin123')
  await page.getByRole('button', { name: 'Masuk', exact: true }).click()
  await expect(page).toHaveURL(/dashboard/)
  await page.evaluate(() => { window.history.pushState({}, '', '/rapor'); window.dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page.getByRole('heading', { name: 'Rapor Semester', exact: true })).toBeVisible()
  const klass = page.getByLabel('Kelas rapor')
  await expect(klass.locator('option')).toHaveCount(2)
  await klass.selectOption({ label: 'Kelas 1 R' })
  await page.getByRole('button', { name: 'Nilai & deskripsi', exact: true }).click()
  await page.getByLabel('Mata pelajaran rapor').selectOption({ label: 'Bahasa Indonesia' })
  await page.getByRole('button', { name: 'Tambah CP', exact: true }).click()
  await page.getByLabel('Label CP 1', { exact: true }).fill('Membaca teks sederhana')
  await page.getByRole('button', { name: 'Tambah CP', exact: true }).click()
  await page.getByLabel('Label CP 2', { exact: true }).fill('Menulis kalimat sederhana')
  await page.getByRole('button', { name: 'Simpan nilai / CP', exact: true }).click()
  await expect(page.getByLabel('Siswa A CP 1', { exact: true })).toBeEnabled()
  await page.getByLabel('Siswa A CP 1', { exact: true }).fill('84.5')
  await page.getByLabel('Siswa A CP 2', { exact: true }).fill('85.5')
  await page.getByLabel('Siswa B CP 1', { exact: true }).fill('90')
  await page.getByLabel('Siswa B CP 2', { exact: true }).fill('80')
  await page.getByLabel('Capaian Siswa A', { exact: true }).fill('Ananda mampu membaca teks dan menulis kalimat sederhana.')
  await page.getByRole('button', { name: 'Simpan nilai / CP', exact: true }).click()
  await expect(page.getByLabel('Capaian Siswa A', { exact: true })).toHaveValue('Ananda mampu membaca teks dan menulis kalimat sederhana.')
  await page.getByRole('button', { name: 'Pengaturan', exact: true }).click()
  await page.getByLabel('Tanggal rapor', { exact: true }).fill('2026-06-01')
  await page.getByRole('button', { name: 'Tambah kegiatan kelas', exact: true }).click()
  await page.getByLabel('Kegiatan kelas 1', { exact: true }).fill('Pramuka')
  await page.getByRole('button', { name: 'Tambah kegiatan kelas', exact: true }).click()
  await page.getByLabel('Kegiatan kelas 2', { exact: true }).fill('Seni Tari')
  await page.getByRole('button', { name: 'Simpan pengaturan', exact: true }).click()
  await expect(page.getByText('Pengaturan rapor tersimpan', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · draft' })
  await page.getByLabel('Catatan wali kelas', { exact: true }).fill('Pertahankan semangat belajar.')
  await page.getByRole('button', { name: 'Tambah ekstrakurikuler', exact: true }).click()
  await page.getByLabel('Nama ekstrakurikuler 1', { exact: true }).selectOption('Pramuka')
  await page.getByLabel('Keterangan ekstrakurikuler 1', { exact: true }).fill('Aktif mengikuti latihan dan mampu bekerja sama dalam regu.')
  await page.getByRole('button', { name: 'Tambah ekstrakurikuler', exact: true }).click()
  await page.getByLabel('Nama ekstrakurikuler 2', { exact: true }).selectOption('Seni Tari')
  await page.getByLabel('Keterangan ekstrakurikuler 2', { exact: true }).fill('Mampu mengikuti gerakan dengan baik dan percaya diri saat tampil bersama kelompok.')
  await page.getByRole('button', { name: 'Simpan catatan', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Simpan catatan', exact: true })).toBeDisabled()
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa B · draft' })
  await expect(page.getByLabel('Nama ekstrakurikuler 1', { exact: true })).toHaveCount(0)
  await page.getByLabel('Peserta didik rapor').selectOption({ label: 'Siswa A · draft' })
  await expect(page.getByLabel('Nama ekstrakurikuler 1', { exact: true })).toHaveValue('Pramuka')
  await expect(page.getByLabel('Keterangan ekstrakurikuler 2', { exact: true })).toHaveValue('Mampu mengikuti gerakan dengan baik dan percaya diri saat tampil bersama kelompok.')
  if (process.env.E2E_REPORT_OUTPUT) await page.getByRole('region', { name: 'Ekstrakurikuler siswa', exact: true }).screenshot({ path: process.env.E2E_REPORT_OUTPUT + '/Isian Ekstrakurikuler.png' })
  await page.getByRole('button', { name: 'Pengaturan', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Kelas ini memiliki ekstrakurikuler' }).uncheck()
  await page.getByRole('button', { name: 'Simpan pengaturan', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Simpan pengaturan', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await expect(page.getByText(/Ekstrakurikuler tidak diaktifkan untuk kelas/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tambah ekstrakurikuler', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Pengaturan', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Kelas ini memiliki ekstrakurikuler' }).check()
  await page.getByRole('button', { name: 'Simpan pengaturan', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Simpan pengaturan', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await expect(page.getByLabel('Nama ekstrakurikuler 1', { exact: true })).toHaveValue('Pramuka')
  await expect(page.getByRole('button', { name: 'Siap diperiksa', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Siap diperiksa', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Finalkan rapor', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Finalkan rapor', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Terbitkan untuk orang tua', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Terbitkan untuk orang tua', exact: true }).click()
  await expect(page.getByText('Status: published · Versi 1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cetak rapor', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Pratinjau cetak rapor' })).toBeVisible()
  await expect(page.getByTitle('PDF rapor')).toHaveAttribute('src', /^blob:/)
  await page.getByRole('button', { name: 'Tutup', exact: true }).click()
  await page.getByRole('button', { name: 'Leger', exact: true }).click()
  await page.getByRole('button', { name: 'Muat leger', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Siswa A', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('tutor mapel melihat kelas penugasannya dan tidak dapat menerbitkan rapor', async ({ page }) => {
  test.skip(process.env.E2E_RAPOR_ISOLATED !== '1', 'Memerlukan database harness terisolasi.')
  await page.goto('/')
  await page.getByPlaceholder('Masukkan username atau email').fill('guru-rapor')
  await page.getByPlaceholder('Masukkan password').fill('Guru12345')
  await page.getByRole('button', { name: 'Masuk', exact: true }).click()
  await expect(page).toHaveURL(/dashboard/)
  await page.evaluate(() => { window.history.pushState({}, '', '/nilai'); window.dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page.getByRole('heading', { name: 'Nilai Sumatif CP' })).toBeVisible()
  await page.getByLabel('Kelas rapor').selectOption({ label: 'Kelas 1 R' })
  await page.getByLabel('Mata pelajaran rapor').selectOption({ label: 'Bahasa Indonesia' })
  await expect(page.getByLabel('Siswa B CP 1', { exact: true })).toBeEnabled()
  await page.getByLabel('Siswa B CP 1', { exact: true }).fill('88')
  await page.getByRole('button', { name: 'Simpan nilai / CP', exact: true }).click()
  await expect(page.getByLabel('Siswa B CP 1', { exact: true })).toHaveValue('88')
  await page.getByRole('button', { name: 'Pemeriksaan & cetak', exact: true }).click()
  await expect(page.getByText(/Pemeriksaan rapor dilakukan wali kelas atau admin/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Terbitkan untuk orang tua', exact: true })).toHaveCount(0)
})
